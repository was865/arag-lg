def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    d = Document()
    d.styles["Normal"].font.size = Pt(10.5)
    d.add_heading("社内研修ハンドブック 品質保証コース", level=0)
    d.add_heading("本書について", level=1)
    d.add_paragraph("品質保証コースの受講者向けの学習ハンドブック。章ごとに学習目標とまとめを置く。")
    d.add_heading("目 次", level=1)
    t = d.add_table(rows=len(TOC), cols=2)
    t.style = "Table Grid"
    for i, (a, b) in enumerate(TOC):
        t.cell(i, 0).text, t.cell(i, 1).text = a, b
    d.add_heading("コースの案内", level=1)
    d.add_paragraph("各章を 1 週間で学ぶ。模擬試験は全章を学んだあとに受ける。")

    def door(label: str) -> None:
        # 章の扉は見出しの書式にしない（太字の段落だけ。解析では本文になる）
        p = d.add_paragraph()
        r = p.add_run(label)
        r.bold = True
        r.font.size = Pt(20)
        d.add_paragraph("この章の学習目標: 章の終わりの確認問題に答えられるようになる。")

    for n, sections in enumerate(CHAPTERS, start=1):
        door(f"第 {n} 章")
        for h, body in sections:
            d.add_heading(h, level=1)
            d.add_paragraph(body)
    door("補遺")
    d.add_heading("規格改訂で変わった点", level=1)
    d.add_paragraph("2026 年の改訂で、リスクに基づく考え方が全章に入った。")
    door("模擬試験")
    # 問いの見出しにも「第N章」と節の題が出る（実際の文書と同じく、章を問う検索がこちらに当たりやすい）
    for i in range(1, 41):
        k = (i - 1) % 5 + 1
        topic = CHAPTERS[k - 1][(i - 1) // 5][0].split(" ", 1)[1]
        d.add_heading(f"Q{i} 第{k}章 {topic}", level=1)
        d.add_paragraph(f"問 {i}: 第{k}章の範囲から出題。「{topic}」について正しいものを選べ。正解は B。")
    door("付録")
    for h, body in [
        ("試験の事実と各章の一言", "試験は 90 分・40 問・合格は 70%。"),
        ("用語集 不適合", "要求事項を満たしていないこと。"),
        ("用語集 是正処置", "不適合の原因を除き、再発を防ぐ処置。"),
        ("用語集 予防処置", "起こりうる不適合の原因を除く処置。"),
        ("用語集 トレーサビリティ", "履歴・適用・所在をたどれること。"),
    ]:
        d.add_heading(h, level=1)
        d.add_paragraph(body)
    d.save(OUT / NAME)
    print(NAME)


if __name__ == "__main__":
    main()
