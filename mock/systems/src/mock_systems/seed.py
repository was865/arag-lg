def build(out: Path) -> None:
    """システムごとの SQLite のファイルを作る（あれば作り直す）。"""
    out.mkdir(parents=True, exist_ok=True)
    _write(
        out / "erp.db",
        {
            "parts": ("part_no, name, models, std_price, reorder_point, supplier_code, status", PARTS),
            "suppliers": ("code, name, location, lead_days, contact", SUPPLIERS),
            "stock_moves": (
                "date, part_no, kind, qty, ref, note",
                [("2026-09-30", p, "棚卸", q, "INV-2026-09", "9月末の棚卸の残高") for p, q in OPENING.items()] + MOVES,
            ),
            "purchase_orders": (
                "po_no, part_no, qty, unit_cost, ordered_on, due_on, received_on, status",
                PURCHASE_ORDERS,
            ),
        },
    )
    _write(
        out / "cmms.db",
        {
            "equipment": ("id, name, location, installed", EQUIPMENT),
            "work_records": ("date, equipment_id, work, staff, downtime_min, procedure", WORK_RECORDS),
            "work_orders": (
                "wo_no, equipment_id, title, status, assignee, opened_on, due_on, closed_on",
                WORK_ORDERS,
            ),
        },
    )
    _write(
        out / "directory.db",
        {"employees": ("emp_no, name, dept, title, extension, private_phone", EMPLOYEES)},
    )
    _write(
        out / "tickets.db",
        {
            "issues": ("no, title, source, assignee, due, status, opened_on, closed_on", ISSUES),
            "comments": ("issue_no, at, author, body", COMMENTS),
        },
    )


def _write(path: Path, tables: dict[str, tuple[str, Sequence[Sequence[object]]]]) -> None:
    path.unlink(missing_ok=True)
    con = sqlite3.connect(path)
    try:
        for name, (cols, rows) in tables.items():
            con.execute(f"CREATE TABLE {name} ({cols})")
            marks = ", ".join("?" for _ in cols.split(","))
            con.executemany(f"INSERT INTO {name} VALUES ({marks})", rows)
        con.commit()
    finally:
        con.close()


